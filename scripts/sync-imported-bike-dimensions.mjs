/** Derive deterministic collision datums from the shipped, rigged geometry.
 * Run after rebuilding any source model. No assets are fetched by the engine.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const models = { '125': 'ciao', scooter: 'nitro', moped: 'moped', '450': 'fs450', '701': 'r6' };
const wheelbases = { '125': 1.04, scooter: 1.28, moped: 1.1, '450': 1.472, '701': 1.37 };
const data = {};
for (const [id, directory] of Object.entries(models)) {
  const file = path.join(root, 'public/models', directory, 'model.json');
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  const bytes = fs.readFileSync(path.join(path.dirname(file), manifest.binary));
  const binary = new Uint8Array(bytes).buffer;
  const a = manifest.anchors;
  let first;
  for (const part of manifest.parts) {
    if (!['body', 'swingarm', 'shockUpper', 'shockLower'].includes(part.rig)) continue;
    const positions = new Float32Array(binary, part.position.offset, part.position.count * 3);
    const indices = new Uint16Array(binary, part.index.offset, part.index.count);
    for (const i of new Set(indices)) {
      const point = Array.from(positions.subarray(i * 3, i * 3 + 3));
      const y = point[1] - a.rearRadius, z = point[2] - a.rearAxle[2];
      if (z < .04 || Math.hypot(y, z) <= a.rearRadius) continue;
      const angle = Math.acos(-a.rearRadius / Math.hypot(y, z)) - Math.atan2(z, y);
      if (angle > 0 && (!first || angle < first.angle)) first = { point, angle, part };
    }
  }
  if (!first) throw new Error(`No rear contact in ${id}`);
  const material = typeof first.part.material === 'number'
    ? manifest.materials[first.part.material]
    : manifest.materials.find(material => material.name === first.part.material);
  const contactMaterial = material?.paintable || /plastic|paint|tail|bodywork|trim|seat|saddle|rubber/.test(material?.name ?? '')
    ? 'plastic' : 'metal';
  a.tail = first.point;
  delete a.tailMaterial;
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + '\n');
  data[id] = {
    wheelbase: a.rearAxle[2] - a.frontAxle[2],
    frontZ: a.frontAxle[2], frontRadius: a.frontRadius,
    rearZ: a.rearAxle[2], rearRadius: a.rearRadius,
    tail: a.tail, material: contactMaterial,
  };
  console.log(`${id}: rear contact ${first.part.name}, ${(first.angle * 180 / Math.PI).toFixed(2)} degrees`);
}
fs.writeFileSync(path.join(root, 'app/game/importedBikeDimensions.ts'), `/** Generated by scripts/sync-imported-bike-dimensions.mjs from shipped geometry.
 * Synchronous metres for deterministic contacts; no loader or Three.js dependency. */
export const IMPORTED_BIKE_WHEELBASE = Object.freeze(${JSON.stringify(wheelbases)});
const source = ${JSON.stringify(data, null, 2)} as const;
function datum(id: keyof typeof source) {
  const value = source[id], size = IMPORTED_BIKE_WHEELBASE[id] / value.wheelbase;
  return Object.freeze({
    tail: value.tail.map((coordinate) => coordinate * size) as [number, number, number],
    rearAxle: value.rearZ * size,
    rearRadius: value.rearRadius * size,
    frontAxle: value.frontZ * size,
    frontRadius: value.frontRadius * size,
    material: value.material,
  });
}
export const IMPORTED_BIKE_TAIL = Object.freeze({ ${Object.keys(models).map(id => `${JSON.stringify(id)}: datum(${JSON.stringify(id)})`).join(', ')} });
`);
